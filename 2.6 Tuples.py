# Accessing values in Tuples
tuple = ('Math' ,'English', 'Urdu', 'Chemistry')
print(tuple)
print(tuple[1])
print(tuple[1:3])

# Updating Tuples
tuple1 = ('Math' ,'English', 'Urdu', 'Chemistry')
tuple2 = ('1', '2', '3', '4')
tuple3 = tuple1 + tuple2
print(tuple3)

# Delete Tuple elements
tuple = ('Math' ,'English', 'Urdu', 'Chemistry')
print(tuple)
del tuple
print(tuple)